/* ======================= CAN 波特率 =======================
   时钟：APB1 = 42MHz（HCLK 168MHz ÷ 4）
   位时间 = 1(SYNC) + BS1(10TQ) + BS2(3TQ) = 14TQ
   波特率 = 42MHz ÷ (Prescaler × 14)
       Prescaler =  3 → 1 Mbps   （DJI 电机常用值，原来就是它）
                    6 → 500 kbps （张大头 ZDT 出厂常见值，见下）
                   12 → 250 kbps
                   24 → 125 kbps

   张大头电机的 CAN 波特率是电机里的一个参数，两边必须完全一致，
   不一致时电机不 ACK → 本机发十几帧后进 bus-off（AutoBusOff 关着就永久静默，
   总线上就“检测不到 CAN 信号”）。电机屏幕上能直接查到它当前的 CAN 波特率。
   ========================================================= */
#define CAN_BAUD_PRESCALER   6
/* USER CODE END 0 */

CAN_HandleTypeDef hcan1;
CAN_HandleTypeDef hcan2;

/* CAN1 init function */
void MX_CAN1_Init(void)
{

  hcan1.Instance = CAN1;
  hcan1.Init.Prescaler = CAN_BAUD_PRESCALER;
  hcan1.Init.Mode = CAN_MODE_NORMAL;
  hcan1.Init.SyncJumpWidth = CAN_SJW_1TQ;
  hcan1.Init.TimeSeg1 = CAN_BS1_10TQ;
  hcan1.Init.TimeSeg2 = CAN_BS2_3TQ;
  hcan1.Init.TimeTriggeredMode = DISABLE;
  hcan1.Init.AutoBusOff = ENABLE;      /* 进 bus-off 后硬件自动恢复，不会永久哑巴 */
  hcan1.Init.AutoWakeUp = DISABLE;
  hcan1.Init.AutoRetransmission = DISABLE;   /* 只发一次，不重发（力矩/读取命令用不到重发，避免邮箱卡死） */
  hcan1.Init.ReceiveFifoLocked = DISABLE;
  hcan1.Init.TransmitFifoPriority = DISABLE;
  if (HAL_CAN_Init(&hcan1) != HAL_OK)
  {
    Error_Handler();
  }

}
